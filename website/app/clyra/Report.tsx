"use client";

import type { AnalysisResult, Screen } from "./types";
import { AppShell, Brand, Icon, ScanImage } from "./ui";

export default function Report({
  result,
  sidebarOpen,
  setSidebarOpen,
  onNavigate,
  onSignOut,
  onBack,
  onNew,
}: {
  result: AnalysisResult;
  sidebarOpen: boolean;
  setSidebarOpen: (value: boolean) => void;
  onNavigate: (screen: Screen) => void;
  onSignOut: () => void;
  onBack: () => void;
  onNew: () => void;
}) {
  const maskImage = result.maskImage || result.sourceImage;
  const overlayImage = result.overlayImage || result.sourceImage;
  const hasStage3 = result.inputMode === "sequence";

  return (
    <AppShell current="report" title="" sidebarOpen={sidebarOpen} setSidebarOpen={setSidebarOpen} onNavigate={onNavigate} onSignOut={onSignOut}>
      <header className="report-toolbar no-print">
        <button className="text-button report-back" onClick={onBack}><Icon name="arrow" /> Back to Results</button>
        <h1>Final CLYRA Report</h1>
        <div>
          <button className="button button--ghost" onClick={() => window.print()}><Icon name="print" /> Print</button>
          <button className="button button--outline" onClick={() => window.print()}><Icon name="download" /> Download PDF</button>
          <button className="button button--primary" onClick={onNew}><Icon name="plus" /> New Analysis</button>
        </div>
      </header>

      <article className="report-sheet">
        <section className="report-heading">
          <Brand compact />
          <div>
            <p className="eyebrow eyebrow--blue">AI-Based Brain CT Analysis System</p>
            <h1>Final CLYRA Report</h1>
            <p><strong>Case ID:</strong> {result.caseId}</p>
            <p><strong>Generated:</strong> {result.generatedAt}</p>
            <p><strong>Input Mode:</strong> {hasStage3 ? "Five-Slice PNG Sequence" : "Single CT Image"}</p>
          </div>
          <div className="report-summary">
            <h2><span>1</span> Analysis Summary</h2>
            <dl>
              <div><dt>CT Category</dt><dd className="danger-text">{result.category}</dd></div>
              <div><dt>Confidence</dt><dd>{result.confidence.toFixed(2)}%</dd></div>
              <div><dt>Lesion Status</dt><dd className="danger-text">{result.lesionDetected ? "Detected" : "Not detected"}</dd></div>
              {hasStage3 && <div><dt>Stage 3 Status</dt><dd className="success-text">{result.stage3Status}</dd></div>}
            </dl>
          </div>
        </section>

        <div className={`report-body ${!hasStage3 ? "report-body--single" : ""}`}>
          <section className="report-section imaging-findings">
            <h2><span>2</span> Imaging Findings</h2>
            <div className="imaging-trio">
              <figure><figcaption>Original CT</figcaption><ScanImage src={result.sourceImage} alt="Original center CT" /></figure>
              <figure><figcaption>Lesion Mask</figcaption><ScanImage src={maskImage} alt="Predicted lesion mask" mask={result.isDemo} /></figure>
              <figure><figcaption>Segmentation Overlay</figcaption><ScanImage src={overlayImage} alt="Segmentation overlay" overlay={result.isDemo} /></figure>
            </div>
          </section>
          {hasStage3 && (
            <section className="report-section">
              <h2><span>3</span> Hemorrhage Subtype Probabilities</h2>
              <div className="subtype-list report-subtypes">
                {result.subtypes.map((item) => (
                  <div key={item.code}>
                    <span>{item.code}</span>
                    <i><b style={{ width: `${item.probability}%` }} /></i>
                    <strong>{item.probability}%</strong>
                    <em className={item.detected ? "detected" : ""}>{item.detected ? "Detected" : "Below threshold"}</em>
                  </div>
                ))}
              </div>
            </section>
          )}
        </div>

        <section className="report-section impression">
          <h2><span>{hasStage3 ? "4" : "3"}</span> AI-Assisted Impression</h2>
          <p>{result.impression}</p>
        </section>
        <section className="clinical-warning">
          <Icon name="alert" size={44} />
          <div><h2>Clinical Review Required</h2><p>This report is generated by an AI-assisted decision-support system and must be reviewed by a qualified physician. It does not replace clinical judgment.</p></div>
        </section>
        <footer className="report-footer">
          <div>
            <strong>Model Versions</strong>
            <span>Stage 1: DenseNet121 v1.0</span>
            <span>Stage 2: U-Net + EfficientNet-B3 v1.0</span>
            {hasStage3 && <span>Stage 3: EfficientNet-B0 + BiGRU v1.0</span>}
          </div>
          <div><strong>Report ID</strong><span>{result.caseId}-R1</span><span>CLYRA v1.0.0</span></div>
          <p>CLYRA • See it. Map it. Know it. • Confidential clinical decision-support output</p>
        </footer>
        {result.isDemo && <div className="demo-watermark">ILLUSTRATIVE DEMO</div>}
      </article>
    </AppShell>
  );
}
